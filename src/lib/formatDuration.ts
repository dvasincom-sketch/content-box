/**
 * Длительность видео (секунды) → человекочитаемая строка.
 *
 *  - >= 1 часа  → «Ч:ММ:СС» (например 1:40:20),
 *  - < 1 часа   → «М:СС»    (например 5:03).
 *
 * Раньше несколько мест показывали минуты:секунды даже для длинных видео —
 * получалось «100:20» (сто минут), что непривычно читателю. Теперь длинное
 * видео читается как часы:минуты:секунды. Формат совпадает с плеером
 * (SelfHostedPlayer.fmtTime), чтобы длительность везде выглядела одинаково.
 *
 * Пустая строка для отсутствующей/нулевой длительности — вызовы вида
 * `fmtDur(x) && (...)` продолжают работать (пустая строка ложна).
 */
export function formatDuration(sec: number | null | undefined): string {
  if (!sec || !Number.isFinite(sec) || sec <= 0) return ''
  const s = Math.floor(sec % 60)
  const m = Math.floor(sec / 60) % 60
  const h = Math.floor(sec / 3600)
  const pad = (n: number) => String(n).padStart(2, '0')
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`
}
